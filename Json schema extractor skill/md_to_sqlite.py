def process_md_file(
    md_path: str,
    conn: sqlite3.Connection,
) -> dict:
    """
    Process a single .md file:
      1. Parse all JSON blocks
      2. Use SchemaManifest to CREATE TABLEs
      3. Use ExtractionResult blocks to INSERT rows
    Returns a summary dict.
    """
    source_file = Path(md_path).name
    print(f"\n{'='*60}")
    print(f"Processing: {source_file}")
    print(f"{'='*60}")

    text = Path(md_path).read_text(encoding="utf-8")
    blocks = extract_json_blocks(text)
    manifest, extractions = split_blocks(blocks)

    print(f"  JSON blocks found: {len(blocks)}")
    print(f"  Manifest: {'✓' if manifest else '✗ (missing — will infer from ExtractionResults)'}")
    print(f"  Extraction blocks: {len(extractions)}")

    doc_name = manifest.get("document_name") if manifest else None

    # Detect file type (initial full doc vs component-level)
    file_type, component_name = detect_file_type(text, extractions)
    if file_type == "component":
        print(f"  File type: component  [{component_name}]")
    elif file_type == "initial":
        print(f"  File type: initial (full document / multi-component)")
    else:
        print(f"  File type: unknown")

    # ── Step 1: CREATE TABLES from SchemaManifest ──────────────────────────
    tables_created = 0
    if manifest:
        # Verify total_tables count
        declared = manifest.get("total_tables", len(manifest.get("tables", [])))
        actual   = len(manifest.get("tables", []))
        if declared != actual:
            print(f"  ⚠ SchemaManifest total_tables={declared} but tables array has {actual} — using array")

        for entry in manifest.get("tables", []):
            tname = entry.get("table_name", "")
            if not tname:
                continue
            # Find rows for this table to enable runtime PK verification
            ex_for_table = next(
                (e for e in extractions if e.get("table_name") == tname), {}
            )
            table_rows = ex_for_table.get("rows") or []
            ddl = build_create_table(tname, entry, rows=table_rows)
            try:
                conn.execute(ddl)
                tables_created += 1
                print(f"  ✓ Table ready: {safe_table_name(tname)}")
            except sqlite3.OperationalError as e:
                print(f"  ⚠ Could not create {tname}: {e}")
    else:
        # No manifest — infer table schemas from ExtractionResult fields
        print("  ℹ No SchemaManifest — inferring schemas from ExtractionResult fields")
        for ex in extractions:
            tname = ex.get("table_name", "")
            if not tname:
                continue
            # Build a synthetic manifest entry from fields[]
            ddl_cols = []
            for f in (ex.get("fields") or []):
                ddl_cols.append({
                    "name":           f.get("name", ""),
                    "sql_type":       f.get("sql_type", "TEXT"),
                    "nullable":       f.get("nullable", True),
                    "is_primary_key": f.get("is_primary_key", False),
                })
            synthetic_entry = {
                "table_name":     tname,
                "ddl_columns":    ddl_cols,
                "lineage_columns": [],
            }
            table_rows = ex.get("rows") or []
            ddl = build_create_table(tname, synthetic_entry, rows=table_rows)
            try:
                conn.execute(ddl)
                tables_created += 1
                print(f"  ✓ Table ready (inferred): {safe_table_name(tname)}")
            except sqlite3.OperationalError as e:
                print(f"  ⚠ Could not create {tname}: {e}")

    # ── Step 2: INSERT rows from ExtractionResult blocks ──────────────────
    total_rows = 0
    for ex in extractions:
        tname    = ex.get("table_name", "")
        rows     = ex.get("rows") or []
        sec_path = ex.get("section_path", "")
        parent   = ex.get("parent_component", "")
        src_rows = ex.get("source_row_count", len(rows))

        if not tname or not rows:
            continue

        n = insert_rows(conn, tname, rows, sec_path, parent, src_rows, source_file)
        total_rows += n
        print(f"  ✓ Inserted {n:>4} rows → {safe_table_name(tname)}")

        # Update registry
        manifest_entry = {}
        if manifest:
            manifest_entry = next(
                (t for t in manifest.get("tables", []) if t.get("table_name") == tname),
                {}
            )
        manifest_entry["section_path"]     = sec_path
        manifest_entry["parent_component"] = parent
        manifest_entry["schema_version"]   = ex.get("schema_version", 1)
        manifest_entry["content_type"]     = ex.get("content_type", "")
        manifest_entry["table_name"]       = tname
        upsert_registry(conn, source_file, doc_name, manifest_entry, n)

    conn.commit()
    result = {"tables": tables_created, "sections": len(extractions), "rows": total_rows}
    print(f"\n  Summary: {tables_created} tables | {len(extractions)} sections | {total_rows} rows")

    # Register this file in the document index
    upsert_document_index(conn, source_file, doc_name, file_type, component_name, result)
    conn.commit()

    result["file_type"]      = file_type
    result["component_name"] = component_name
    return result


