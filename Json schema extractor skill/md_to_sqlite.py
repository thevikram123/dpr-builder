def run(
    md_glob: str = MD_GLOB,
    file_list: list[str] | None = None,
    db_path: str = DB_PATH,
    reset: bool = RESET_DB,
):
    """
    Process .md extraction files into a single SQLite database.

    Args:
        md_glob:   Glob pattern for .md files (used if file_list is None)
        file_list: Explicit list of file paths (used by upload_and_run)
        db_path:   Output SQLite database path
        reset:     If True, delete the DB before running (testing only)

    Examples:
        run()                              # all *.md in working dir
        run("noida_*.md")                  # specific glob
        run(file_list=["c1.md","c2.md"])   # explicit list
        run(reset=True)                    # wipe and rebuild
    """
    # Resolve file list
    if file_list is not None:
        md_files = sorted(str(p) for p in file_list)
    else:
        md_files = sorted(glob.glob(md_glob))

    if not md_files:
        src = "file_list" if file_list is not None else f"glob '{md_glob}'"
        print(f"No .md files found from {src}.")
        print("Upload your extraction .md files and re-run.")
        return

    print(f"Files to process: {len(md_files)}")
    for f in md_files:
        print(f"  {Path(f).name}")

    if reset and os.path.exists(db_path):
        os.remove(db_path)
        print(f"\nReset: removed existing {db_path}")

    conn = sqlite3.connect(db_path)
    conn.execute("PRAGMA journal_mode=WAL")
    conn.execute("PRAGMA foreign_keys=ON")
    create_registry_table(conn)
    conn.commit()

    totals = {"files": 0, "tables": 0, "sections": 0, "rows": 0}
    file_results = []

    for md_path in md_files:
        result = process_md_file(md_path, conn)
        totals["files"]    += 1
        totals["tables"]   += result["tables"]
        totals["sections"] += result["sections"]
        totals["rows"]     += result["rows"]
        file_results.append((Path(md_path).name, result))

    conn.close()

    # ── Final summary ─────────────────────────────────────────────────────
    print(f"\n{'='*60}")
    print("DONE")
    print(f"  Files processed : {totals['files']}")
    print(f"  Tables created  : {totals['tables']}")
    print(f"  Sections loaded : {totals['sections']}")
    print(f"  Rows inserted   : {totals['rows']}")
    print(f"  Database        : {os.path.abspath(db_path)}")

    # Per-file breakdown
    print(f"\nPer-file breakdown:")
    for fname, r in file_results:
        ftype = r.get("file_type", "unknown")
        comp  = r.get("component_name") or ""
        label = f"[{ftype}] {comp}" if comp else f"[{ftype}]"
        print(f"  {fname:<40} {label:<45} {r['sections']:>3} sections  {r['rows']:>5} rows")

    # Table inventory
    conn = sqlite3.connect(db_path)
    print(f"\n{'─'*60}")
    print("Tables in database:")
    rows = conn.execute(
        "SELECT name FROM sqlite_master WHERE type='table' ORDER BY name"
    ).fetchall()
    system_tables = {"_extraction_registry", "_document_index", "sqlite_sequence"}
    data_tables   = [(r[0],) for r in rows if r[0] not in system_tables]
    system_only   = [(r[0],) for r in rows if r[0] in system_tables]

    for (name,) in data_tables:
        count = conn.execute(f'SELECT COUNT(*) FROM "{name}"').fetchone()[0]
        print(f"  {name:<60} {count:>6} rows")

    print(f"\nSystem tables:")
    for (name,) in system_only:
        count = conn.execute(f'SELECT COUNT(*) FROM "{name}"').fetchone()[0]
        print(f"  {name:<60} {count:>6} rows")

    # Document index
    print(f"\nDocument index (_document_index):")
    idx_rows = conn.execute(
        "SELECT source_file, file_type, component_name, tables_created, rows_inserted FROM _document_index ORDER BY file_type, source_file"
    ).fetchall()
    for r in idx_rows:
        comp = r[2] or ""
        print(f"  [{r[1]:<10}] {r[0]:<35} {comp:<40} {r[3]} tables  {r[4]} rows")

    conn.close()
    print(f"{'='*60}")


