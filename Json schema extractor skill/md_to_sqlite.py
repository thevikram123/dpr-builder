def extract_json_blocks(md_text: str) -> list[dict]:
    """Pull every ```json ... ``` block out of markdown text."""
    pattern = re.compile(r'```json\s*(.*?)\s*```', re.DOTALL)
    blocks = []
    for match in pattern.finditer(md_text):
        try:
            obj = json.loads(match.group(1))
            blocks.append(obj)
        except json.JSONDecodeError as e:
            print(f"  ⚠ JSON parse error (skipping block): {e}")
    return blocks


def split_blocks(blocks: list[dict]) -> tuple[dict | None, list[dict]]:
    """
    Separate one SchemaManifest from ExtractionResult blocks.
    Returns (manifest_or_None, [extraction_results])
    """
    manifest = None
    extractions = []
    for b in blocks:
        if b.get("type") == "SchemaManifest":
            manifest = b
        elif b.get("should_extract") is True and b.get("rows") is not None:
            extractions.append(b)
    return manifest, extractions


def safe_table_name(name: str) -> str:
    """Ensure table name is safe SQL — lowercase, underscores, no reserved words."""
    SQL_RESERVED = {
        "order", "group", "select", "where", "table", "index",
        "values", "insert", "update", "delete", "create", "drop",
        "from", "join", "set", "by", "as", "is", "in", "on",
        "not", "and", "or", "null"
    }
    safe = re.sub(r'[^a-z0-9_]', '_', name.lower())[:60]
    safe = re.sub(r'_+', '_', safe).strip('_')
    if safe in SQL_RESERVED:
        safe = f"tbl_{safe}"
    return safe


def safe_col_name(name: str) -> str:
    """Ensure column name is safe SQL."""
    SQL_COL_RESERVED = {"type", "id", "name", "value", "index", "order", "group"}
    safe = re.sub(r'[^a-z0-9_]', '_', name.lower())
    if safe in SQL_COL_RESERVED:
        safe = f"col_{safe}"
    return safe


def ddl_col_fragment(col: dict) -> str:
    """Build a single column definition string for CREATE TABLE."""
    name = safe_col_name(col["name"])
    sql_type = col.get("sql_type", "TEXT")

    # Compliance columns must always be TEXT — guard against bool/INTEGER mistake
    if "compliance" in name and sql_type == "INTEGER":
        sql_type = "TEXT"

    # Requirement text columns must always be nullable — source docs routinely
    # have blank requirement cells (e.g. DCS.011–DCS.021 in core switch tables)
    NULLABLE_ALWAYS = {
        "minimum_requirement", "min_requirement",
        "minimum_required_specifications", "minimum_requirement_description",
        "minimum_required_description",
    }
    if name in NULLABLE_ALWAYS:
        nullable = True
    else:
        nullable = col.get("nullable", True)

    parts = [f'"{name}" {sql_type}']
    if not nullable:
        parts.append("NOT NULL")
    if col.get("is_primary_key", False):
        parts.append("PRIMARY KEY")
    return " ".join(parts)


def build_create_table(table_name: str, manifest_entry: dict, rows: list | None = None) -> str:
    """
    Generate CREATE TABLE IF NOT EXISTS DDL from a SchemaManifest entry.
    Always appends lineage columns + auto-increment _row_id if no PK defined.

    rows: if provided, used to verify is_primary_key at the data level —
          overrides manifest if duplicates or nulls are detected.
    """
    safe_name = safe_table_name(table_name)
    ddl_cols = manifest_entry.get("ddl_columns", [])

    # Runtime PK safety check: verify claimed PKs against actual row data
    if rows:
        for col in ddl_cols:
            if col.get("is_primary_key", False):
                field = col["name"]
                values = [r.get(field) for r in rows]
                has_null = any(v is None or v == "N/A" for v in values)
                has_dup  = len(set(str(v) for v in values if v is not None)) < len([v for v in values if v is not None])
                if has_null or has_dup:
                    col = dict(col)  # don't mutate original
                    col["is_primary_key"] = False
                    ddl_cols = [c if c["name"] != field else col for c in ddl_cols]

    has_pk = any(c.get("is_primary_key", False) for c in ddl_cols)

    col_defs = []

    # Auto-increment PK when source has no unique key
    if not has_pk:
        col_defs.append('"_row_id" INTEGER PRIMARY KEY AUTOINCREMENT')

    for col in ddl_cols:
        col_defs.append(ddl_col_fragment(col))

    # Fixed lineage columns
    fixed_lineage = [
        {"name": "_section_path",    "sql_type": "TEXT"},
        {"name": "_parent_component","sql_type": "TEXT"},
        {"name": "_source_row_count","sql_type": "INTEGER"},
        {"name": "_extracted_at",    "sql_type": "TEXT"},
        {"name": "_source_file",     "sql_type": "TEXT"},
    ]
    seen = {safe_col_name(c["name"]) for c in ddl_cols}
    for col in fixed_lineage:
        cname = safe_col_name(col["name"])
        if cname not in seen:
            col_defs.append(f'"{cname}" {col["sql_type"]}')

    return (
        f'CREATE TABLE IF NOT EXISTS "{safe_name}" (\n'
        + ',\n'.join(f'    {c}' for c in col_defs)
        + '\n)'
    )


def ensure_columns(conn: sqlite3.Connection, table_name: str, row_keys: list[str]):
    """
    ALTER TABLE to add any columns present in row data but missing from table.
    Prevents insert failures when a new .md file has extra fields.
    """
    safe_name = safe_table_name(table_name)
    cursor = conn.execute(f'PRAGMA table_info("{safe_name}")')
    existing = {row[1].lower() for row in cursor.fetchall()}

    for key in row_keys:
        safe_key = safe_col_name(key)
        if safe_key not in existing:
            conn.execute(f'ALTER TABLE "{safe_name}" ADD COLUMN "{safe_key}" TEXT')
            print(f"    ALTER TABLE {safe_name}: added column {safe_key}")


def insert_rows(
    conn: sqlite3.Connection,
    table_name: str,
    rows: list[dict],
    section_path: str,
    parent_component: str,
    source_row_count: int,
    source_file: str,
):
    """
    Idempotent bulk insert.
    Delete existing rows for this (source_file, section_path) before inserting.
    """
    safe_name = safe_table_name(table_name)
    now = datetime.now(timezone.utc).isoformat()

    # Idempotent: remove previous rows from this exact section + file
    conn.execute(
        f'DELETE FROM "{safe_name}" WHERE _source_file = ? AND _section_path = ?',
        (source_file, section_path)
    )

    if not rows:
        return 0

    # Ensure all columns in rows exist in the table
    all_keys = set()
    for row in rows:
        all_keys.update(row.keys())
    ensure_columns(conn, table_name, list(all_keys))

    inserted = 0
    for row in rows:
        # Build insert dict with safe column names + lineage
        safe_row = {safe_col_name(k): v for k, v in row.items()}
        safe_row["_section_path"]     = section_path
        safe_row["_parent_component"] = parent_component
        safe_row["_source_row_count"] = source_row_count
        safe_row["_extracted_at"]     = now
        safe_row["_source_file"]      = source_file

        cols = ', '.join(f'"{k}"' for k in safe_row)
        placeholders = ', '.join('?' for _ in safe_row)
        values = list(safe_row.values())

        try:
            conn.execute(
                f'INSERT INTO "{safe_name}" ({cols}) VALUES ({placeholders})',
                values
            )
            inserted += 1
        except sqlite3.IntegrityError as e:
            # PRIMARY KEY violation — shouldn't happen after is_primary_key fixes
            # but handle gracefully: insert without PK column
            print(f"    ⚠ IntegrityError on {safe_name}: {e} — skipping row")

    return inserted


def create_registry_table(conn: sqlite3.Connection):
    """
    _extraction_registry tracks every .md file processed and its manifest.
    Useful for debugging and the downstream DPR builder.
    """
    conn.execute("""
        CREATE TABLE IF NOT EXISTS _extraction_registry (
            registry_id      TEXT PRIMARY KEY,
            source_file      TEXT NOT NULL,
            document_name    TEXT,
            table_name       TEXT NOT NULL,
            physical_table   TEXT NOT NULL,
            schema_version   INTEGER,
            content_type     TEXT,
            section_path     TEXT,
            parent_component TEXT,
            row_count        INTEGER,
            processed_at     TEXT NOT NULL
        )
    """)

    # _document_index: one row per .md file, classifies initial vs component
    conn.execute("""
        CREATE TABLE IF NOT EXISTS _document_index (
            file_id          TEXT PRIMARY KEY,
            source_file      TEXT NOT NULL UNIQUE,
            document_name    TEXT,
            file_type        TEXT NOT NULL,   -- 'initial' | 'component' | 'unknown'
            component_name   TEXT,            -- e.g. "Component 2: CCTV"
            tables_created   INTEGER DEFAULT 0,
            sections_loaded  INTEGER DEFAULT 0,
            rows_inserted    INTEGER DEFAULT 0,
            processed_at     TEXT NOT NULL
        )
    """)


def detect_file_type(md_text: str, extractions: list[dict]) -> tuple[str, str | None]:
    """
    Classify a .md file as 'initial' (full document) or 'component' (single component).
    Returns (file_type, component_name_or_None).

    Heuristics:
      - If all extractions share the same parent_component → component-level file
      - If extractions span multiple parent_components → initial/full document
      - If no extractions (DocumentMap only) → initial
    """
    if not extractions:
        return "initial", None

    parents = {ex.get("parent_component", "") for ex in extractions if ex.get("parent_component")}

    if len(parents) == 1:
        return "component", parents.pop()
    elif len(parents) > 1:
        return "initial", None
    else:
        return "unknown", None


def upsert_document_index(
    conn: sqlite3.Connection,
    source_file: str,
    doc_name: str | None,
    file_type: str,
    component_name: str | None,
    result: dict,
):
    file_id = hashlib.sha256(source_file.encode()).hexdigest()[:16]
    conn.execute("""
        INSERT OR REPLACE INTO _document_index
        (file_id, source_file, document_name, file_type, component_name,
         tables_created, sections_loaded, rows_inserted, processed_at)
        VALUES (?,?,?,?,?,?,?,?,?)
    """, (
        file_id,
        source_file,
        doc_name,
        file_type,
        component_name,
        result.get("tables", 0),
        result.get("sections", 0),
        result.get("rows", 0),
        datetime.now(timezone.utc).isoformat(),
    ))


def upsert_registry(
    conn: sqlite3.Connection,
    source_file: str,
    doc_name: str | None,
    entry: dict,
    row_count: int,
):
    registry_id = hashlib.sha256(
        f"{source_file}:{entry.get('section_path','')}:{entry.get('table_name','')}".encode()
    ).hexdigest()[:16]

    conn.execute("""
        INSERT OR REPLACE INTO _extraction_registry
        (registry_id, source_file, document_name, table_name, physical_table,
         schema_version, content_type, section_path, parent_component,
         row_count, processed_at)
        VALUES (?,?,?,?,?,?,?,?,?,?,?)
    """, (
        registry_id,
        source_file,
        doc_name,
        entry.get("table_name", ""),
        safe_table_name(entry.get("table_name", "")),
        entry.get("schema_version", 1),
        entry.get("content_type", ""),
        entry.get("section_path", ""),
        entry.get("parent_component", ""),
        row_count,
        datetime.now(timezone.utc).isoformat(),
    ))


